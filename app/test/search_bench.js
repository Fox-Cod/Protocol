function run(server, gold) {
  const file = path.join(DATA, server + '.json');
  if (!fs.existsSync(file)) {
    console.log(`  ПРОПУСК ${server}: нет ${file}`);
    return null;
  }
  const laws = JSON.parse(fs.readFileSync(file, 'utf8'));
  const codes = {};
  Object.keys(laws).forEach((k) => { codes['law:' + k] = laws[k]; });
  // Приложение держит правила проекта в ТОМ ЖЕ индексе, что и кодексы.
  // Без них тест врал: правила короткие и на живых запросах перебивают
  // кодекс, а замер этого не видел и показывал 100% там, где в приложении
  // Уголовный кодекс в контекст не попадал вовсе.
  const rulesFile = path.join(DATA, 'rules.json');
  if (fs.existsSync(rulesFile)) {
    const rules = JSON.parse(fs.readFileSync(rulesFile, 'utf8'));
    Object.keys(rules).forEach((k) => { codes['rules:' + k] = rules[k]; });
  }
  const t0 = Date.now();
  const idx = new ProtocolAI.ServerIndex(server, codes);
  const buildMs = Date.now() - t0;

  let r8 = 0, r30 = 0, mrr = 0;
  const misses = [];
  for (const [q, want] of gold) {
    const hits = idx.searchBalanced(q, 30, 8);
    let rank = 0;
    for (let i = 0; i < hits.length; i++) {
      const d = hits[i].doc;
      if ((d.code_short || '').toUpperCase() === 'УК' && want.indexOf(String(d.num)) >= 0) { rank = i + 1; break; }
    }
    if (rank && rank <= 8) r8++;
    if (rank && rank <= 30) r30++;
    if (rank) mrr += 1 / rank;
    if (!rank || rank > 8) misses.push(`${q} → ждали ${want.join('/')}, ранг ${rank || '—'}`);
  }
  const n = gold.length;
  console.log(`\n${server}  (${idx.N} статей, индекс ${buildMs} мс)`);
  console.log(`  recall@8   ${r8}/${n}  ${Math.round(r8 / n * 100)}%`);
  console.log(`  recall@30  ${r30}/${n}  ${Math.round(r30 / n * 100)}%`);
  console.log(`  MRR        ${(mrr / n).toFixed(3)}`);
  if (misses.length) console.log('  вне топ-8:\n    ' + misses.join('\n    '));
  return { r8, r30, n };
}

